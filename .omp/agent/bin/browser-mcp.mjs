// chrome-devtools MCP launcher (Linux, Windows, macOS). Every session gets a private
// browser profile, so any number of sessions can run at once without a profile lock.
//
//   <agent dir>/browser-profiles/<project>/ exists -> per-session copy of it
//   no profile                                     -> blank profile (--isolated)
//
// <project> is the main repo's directory name (worktrees share it), else the cwd's.
//
// Sign in with `/browser-login` in omp (or `node <this file> login [url]`): it opens the
// browser on the saved profile at [url], else `.omp/browser.json` {"url"}, else the dev
// server this project is running. Closing that browser stamps the profile, and every
// running launcher of the project exits so omp reconnects it on a fresh copy.
//
// stdout belongs to the MCP protocol: this file only ever writes to stderr.

import { spawn, spawnSync } from "node:child_process";
import { constants, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, watchFile, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

import { AGENT_DIR, findBrowser, IS_WINDOWS, projectListeners, projectRoot, run } from "./lib/system.mjs";

const PACKAGE = "chrome-devtools-mcp@1.8.0";
const PROFILES = join(AGENT_DIR, "browser-profiles");
// Same filesystem as PROFILES, so a copy-on-write filesystem (btrfs, XFS, APFS) clones instantly.
const RUNS = join(AGENT_DIR, "browser-runs");

// Regenerated by the browser on demand; skipping them keeps a full copy (NTFS, ext4) small.
const SKIP = new Set([
  "Cache",
  "Code Cache",
  "GPUCache",
  "GrShaderCache",
  "ShaderCache",
  "GraphiteDawnCache",
  "DawnGraphiteCache",
  "DawnWebGPUCache",
  "GPUPersistentCache",
  "CacheStorage",
  "ScriptCache",
  "Crashpad",
  "BrowserMetrics",
  "DeferredBrowserMetrics",
  "lockfile"
]);

function projectName() {
  const common = run("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"]);
  return common ? basename(dirname(common)) : basename(process.cwd());
}

function isAlive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return error.code === "EPERM";
  }
}

function removeDir(path) {
  try {
    rmSync(path, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
  } catch {
    // A browser still holding files (Windows): the next launch sweeps it.
  }
}

/** Copies left behind by a killed session; the owning launcher pid is the suffix. */
function sweepStaleRuns() {
  if (!existsSync(RUNS)) {
    return;
  }
  for (const entry of readdirSync(RUNS)) {
    const pid = Number(entry.slice(entry.lastIndexOf("-") + 1));
    if (!Number.isInteger(pid) || !isAlive(pid)) {
      removeDir(join(RUNS, entry));
    }
  }
}

function copyProfile(source, target) {
  cpSync(source, target, {
    recursive: true,
    mode: constants.COPYFILE_FICLONE,
    filter: (path) => {
      const name = basename(path);
      return !SKIP.has(name) && !name.startsWith("Singleton");
    }
  });
}

/** Windows runs pnpx.cmd through cmd.exe, which needs each argument quoted. */
function spawnServer(args) {
  if (IS_WINDOWS) {
    const quoted = args.map((arg) => `"${arg}"`);
    return spawn("pnpx", quoted, { stdio: "inherit", shell: true, windowsHide: true });
  }
  return spawn("pnpx", args, { stdio: "inherit", detached: true });
}

function killTree(child) {
  if (IS_WINDOWS) {
    if (child.exitCode === null && child.signalCode === null) {
      spawnSync("taskkill", ["/pid", String(child.pid), "/T", "/F"], { stdio: "ignore", windowsHide: true });
    }
    return;
  }
  // The group outlives its leader, so signal it even after the server exited: a browser left behind dies too.
  try {
    process.kill(-child.pid, "SIGTERM");
  } catch {
    // Group already gone.
  }
}

function configuredUrl(root) {
  const file = join(root, ".omp", "browser.json");
  if (!existsSync(file)) {
    return undefined;
  }
  try {
    const { url } = JSON.parse(readFileSync(file, "utf8"));
    return typeof url === "string" && url ? url : undefined;
  } catch (error) {
    console.error(`browser-mcp: ignoring ${file}: ${error.message}`);
    return undefined;
  }
}

/** `value` when it is an http(s) URL; browser.json comes from the (untrusted) repo. */
function webUrl(value) {
  if (!value) {
    return undefined;
  }
  try {
    const { protocol } = new URL(value);
    if (protocol === "http:" || protocol === "https:") {
      return value;
    }
  } catch {
    // Not a URL.
  }
  console.error(`browser-mcp: ignoring non-http(s) URL ${JSON.stringify(value)}`);
  return undefined;
}

/** The lowest port of this project that serves a page (HTML or a redirect), so sidecar ports are skipped. */
async function detectDevServer(root) {
  const ports = [...new Set(projectListeners(root).map((listener) => listener.port))];
  const pages = await Promise.all(
    ports.map(async (port) => {
      const url = `http://localhost:${port}/`;
      try {
        const response = await fetch(url, { redirect: "manual", signal: AbortSignal.timeout(1500) });
        const html = response.headers.get("content-type")?.includes("text/html");
        return html || (response.status >= 300 && response.status < 400) ? { port, url } : undefined;
      } catch {
        return undefined;
      }
    })
  );
  return pages.filter(Boolean).sort((a, b) => a.port - b.port)[0]?.url;
}

const project = projectName();
const profile = join(PROFILES, project);
const stamp = join(PROFILES, `.${project}.signed-in`);
const loginPid = join(PROFILES, `.${project}.login-pid`);
const browser = findBrowser();

if (process.argv[2] === "login") {
  if (!browser) {
    console.error("browser-mcp: no Edge install found; set OMP_BROWSER_EXECUTABLE.");
    process.exit(1);
  }
  // Callers read one status line (prefix "browser-mcp: signing in") and may close the pipe after it.
  const announce = (detail) => console.error(`browser-mcp: signing in "${project}"${detail}. Close the browser when done.`);
  const owner = Number(existsSync(loginPid) ? readFileSync(loginPid, "utf8") : 0);
  if (owner && isAlive(owner)) {
    // A second browser on this profile hands off to the open window and exits at once, which would stamp a sign-in that has not happened.
    announce(" in the window that is already open");
    setInterval(() => {
      if (!isAlive(owner)) {
        process.exit(0);
      }
    }, 1000);
  } else {
    const root = projectRoot();
    const url = webUrl(process.argv[3]) || webUrl(configuredUrl(root)) || (await detectDevServer(root));
    mkdirSync(profile, { recursive: true });
    // `--` ends switch parsing, so a URL can never be read as a browser flag.
    const login = spawn(browser, [`--user-data-dir=${profile}`, "--no-first-run", ...(url ? ["--", url] : [])], {
      stdio: "ignore",
      windowsHide: false
    });
    login.once("spawn", () => {
      writeFileSync(loginPid, String(login.pid));
      announce(url ? ` at ${url}` : " (no dev server found)");
    });
    login.once("error", (error) => {
      console.error(`browser-mcp: could not start ${browser}: ${error.message}`);
      process.exit(1);
    });
    login.once("exit", () => {
      rmSync(loginPid, { force: true });
      writeFileSync(stamp, String(Date.now()));
      process.exit(0);
    });
  }
} else {
  const args = ["-y", PACKAGE, ...(browser ? ["--executablePath", browser] : [])];
  let runDir;
  if (existsSync(profile)) {
    sweepStaleRuns();
    runDir = join(RUNS, `${project}-${process.pid}`);
    mkdirSync(RUNS, { recursive: true });
    copyProfile(profile, runDir);
    args.push("--userDataDir", runDir);
  } else {
    args.push("--isolated");
  }

  const child = spawnServer(args);

  const shutdown = (code) => {
    killTree(child);
    if (runDir) {
      removeDir(runDir);
    }
    process.exit(code);
  };

  child.on("exit", (code, signal) => shutdown(code ?? (signal ? 1 : 0)));
  child.on("error", (error) => {
    console.error(`browser-mcp: failed to start ${PACKAGE}: ${error.message}`);
    shutdown(1);
  });
  for (const signal of IS_WINDOWS ? ["SIGINT", "SIGBREAK"] : ["SIGINT", "SIGTERM", "SIGHUP"]) {
    process.on(signal, () => shutdown(143));
  }
  // A finished login: exit so omp reconnects this server on a copy that carries the new sign-in.
  watchFile(stamp, { interval: 1000 }, (current, previous) => {
    if (current.mtimeMs > previous.mtimeMs) {
      console.error("browser-mcp: new sign-in saved; restarting on it.");
      shutdown(0);
    }
  });
}
